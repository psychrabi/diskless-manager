use std::path::Path;

pub const NVMEOF_FIRMWARE: &str = "snponly-nvmeof.efi";
pub const NVMEOF_CAPABILITY_FLAG: &str = "diskless-nvmeof";

/// Port the dedicated client-enrollment HTTP listener binds to.
///
/// The enrollment listener is deliberately separate from the management API
/// so iPXE clients only ever reach a single, unauthenticated endpoint instead
/// of the full management surface.
pub const ENROLL_PORT: u16 = 4237;

/// Returns a filesystem-safe identifier suitable for a per-client iPXE filename.
#[must_use]
pub fn client_script_slug(client_name: &str) -> String {
    let mut slug = String::with_capacity(client_name.len());
    for byte in client_name.bytes() {
        if byte.is_ascii_alphanumeric() || matches!(byte, b'-' | b'_' | b'.') {
            slug.push((byte as char).to_ascii_lowercase());
        } else {
            slug.push('_');
        }
    }

    if slug.is_empty() {
        "client".to_owned()
    } else {
        slug
    }
}

/// Initiator identity sent by this client's iPXE boot script.
pub fn client_initiator_iqn(client_name: &str) -> String {
    format!(
        "iqn.2026-01.client:client.{}",
        client_script_slug(client_name)
    )
}

#[must_use]
pub fn client_mac_slug(mac: &str) -> String {
    let slug: String = mac
        .chars()
        .filter(|character| character.is_ascii_hexdigit())
        .map(|character| character.to_ascii_lowercase())
        .collect();

    if slug.len() == 12 {
        slug
    } else {
        "unknown".to_owned()
    }
}

#[must_use]
pub fn client_script_path(client_name: &str) -> String {
    format!("{}.ipxe", client_script_slug(client_name))
}

#[must_use]
pub fn client_mac_script_path(mac: &str) -> String {
    format!("clients/{}.ipxe", client_mac_slug(mac))
}

pub(crate) fn is_manager_generated_menu(contents: &str) -> bool {
    contents.contains("# Client-specific iPXE script generated by diskless-manager.")
        || contents.contains("# Super installer boot for ")
        || contents.contains("# Super-session boot denied")
}

#[must_use]
pub fn render_client_script(client_name: &str, target_iqn: &str, http_port: u16) -> String {
    render_client_script_with_mode(client_name, target_iqn, http_port, true, None)
}

/// Boot the installer recorded by an active Super session from the client's
/// existing target, with the working disk exposed as the secondary drive.
#[must_use]
pub fn render_super_client_script(
    client_name: &str,
    target_iqn: &str,
    server_ip: &str,
    media_type: crate::persistence::InstallerMediaType,
    firmware: crate::domain::PxeMode,
    chap: Option<&crate::infrastructure::iscsi::ChapCredentials>,
) -> String {
    let slug = client_script_slug(client_name);
    let initiator_iqn = client_initiator_iqn(client_name);
    let chap_settings = match chap {
        Some(credentials) => format!(
            "set username {}\nset password {}\n",
            credentials.username, credentials.password
        ),
        None => String::new(),
    };
    let label = match media_type {
        crate::persistence::InstallerMediaType::WindowsIso => "Windows installer",
        crate::persistence::InstallerMediaType::WinPe => "Windows WinPE installer",
        crate::persistence::InstallerMediaType::LinuxIso => "Linux installer",
        crate::persistence::InstallerMediaType::OtherIso => "Other installer",
    };
    format!(
        "#!ipxe\ndhcp\n# Super installer boot for {slug} ({}, {label})\nset initiator-iqn {initiator_iqn}\nset target-iqn {target_iqn}\nset keep-san 1\n{chap_settings}sanhook --drive 0x81 iscsi:{server_ip}:::0:{target_iqn} || goto failed\nsanboot --no-describe iscsi:{server_ip}:::2:{target_iqn} || goto failed\n:failed\nimgfetch http://${{next-server}}:{enroll_port}/boot/failed/${{client-mac}} || echo Could not report boot failure\necho Super installer boot failed.\nshell\n",
        firmware.as_str(),
        enroll_port = ENROLL_PORT,
    )
}

#[must_use]
pub fn render_super_boot_denied() -> String {
    "#!ipxe\n# Super-session boot denied until server-side state is repaired.\necho Diskless Manager: installer boot is unavailable; retrying shortly.\nsleep 10\nreboot\n".to_owned()
}

/// iPXE response served to a client that is not yet registered.
///
/// Reuses the session variables set by `autoexec.ipxe` (`boot-url`,
/// `client-mac`), which are preserved across a `chain` into this script.
#[must_use]
pub fn render_enrollment_pending() -> String {
    r##"#!ipxe
echo ##########################################################
echo # Diskless Manager - client enrollment                 #
echo #                                                        #
echo # Client ${client-mac} has been registered.             #
echo # No master image has been assigned yet.                #
echo # Ask an administrator to provision this machine.       #
echo ##########################################################
sleep 30
reboot
"##
    .to_string()
}

/// iPXE response used when assigned storage could not be made ready.
#[must_use]
pub fn render_enrollment_retry() -> String {
    r##"#!ipxe
echo Diskless Manager: storage is not ready yet; retrying shortly.
sleep 10
reboot
"##
    .to_string()
}

/// iPXE response served when the enrollment request itself could not be
/// understood. Retries are deferred so clients poll rather than hammer the
/// server on a broken configuration.
#[must_use]
pub fn render_enrollment_invalid_mac() -> String {
    r##"#!ipxe
echo Diskless Manager: enrollment failed (unrecognized client MAC).
echo Check the boot server network configuration.
sleep 30
reboot
"##
    .to_string()
}

/// iPXE response served to a client whose record is disabled.
///
/// A disabled client must never boot, even if it is fully provisioned:
/// this is the binding gate that e.g. decommissioned or quarantined
/// machines hit. Polls slowly so re-enabling takes effect without hurry.
#[must_use]
pub fn render_enrollment_disabled() -> String {
    r##"#!ipxe
echo ##########################################################
echo # Diskless Manager - client disabled                   #
echo #                                                        #
echo # This machine is disabled by an administrator.         #
echo # Booting is not permitted.                             #
echo ##########################################################
sleep 60
reboot
"##
    .to_string()
}

/// iPXE response that boots WinPE to collect the preboot NIC inventory.
/// The WinPE image reports Boot NIC hardware IDs and reboots; whether the
/// inventory upload succeeds or fails, the client returns to the normal
/// dispatch path instead of hanging in WinPE.
/// Both UEFI image naming and BIOS CPIO naming must match the BCD's boot.wim.
#[must_use]
pub fn render_inventory_boot() -> String {
    r##"#!ipxe
echo ##########################################################
echo # Diskless Manager - network inventory                  #
echo #                                                        #
echo # Booting WinPE to record this machine's Boot NIC.      #
echo # The machine returns to the normal boot menu after.    #
echo ##########################################################
kernel ${boot-url}/boot/winpe/wimboot || goto inventory_failed
initrd ${boot-url}/boot/winpe/BCD BCD || goto inventory_failed
initrd ${boot-url}/boot/winpe/boot.sdi boot.sdi || goto inventory_failed
initrd --name boot.wim ${boot-url}/boot/winpe/boot-inventory.wim boot.wim || goto inventory_failed
boot || goto inventory_failed

:inventory_failed
echo Inventory boot failed; returning to the normal client menu...
chain http://${next-server}:4237/enroll/${client-mac} || shell
"##
    .to_string()
}

/// Render a diagnostic-only Auto PNP block using iPXE's PCI configuration
/// space settings. The scan is intentionally limited to PCI class 02
/// (network controllers); Windows remains the authority for signed INF
/// selection and installation. If the deployed iPXE binary lacks `pciscan`,
/// the block exits silently and the normal boot menu continues.
#[must_use]
pub fn render_auto_pnp_block() -> &'static str {
    r##"clear auto-pnp-addr || goto auto_pnp_done
:auto_pnp_scan
pciscan auto-pnp-addr || goto auto_pnp_done
set auto-pnp-class ${pci/${auto-pnp-addr}.0x0b.1} || goto auto_pnp_done
iseq ${auto-pnp-class} 02 || goto auto_pnp_scan
set auto-pnp-header ${pci/${auto-pnp-addr}.0x0e.1} || goto auto_pnp_done
set auto-pnp-ven ${pci/${auto-pnp-addr}.0x00.2} || goto auto_pnp_done
set auto-pnp-dev ${pci/${auto-pnp-addr}.0x02.2} || goto auto_pnp_done
# A false iseq is an error status; handle both header comparisons.
iseq ${auto-pnp-header} 00 || iseq ${auto-pnp-header} 80 || goto auto_pnp_nonendpoint
goto auto_pnp_endpoint
:auto_pnp_nonendpoint
echo Auto PNP NIC ${auto-pnp-addr:busdevfn}: VEN_${auto-pnp-ven}&DEV_${auto-pnp-dev} (PCI header ${auto-pnp-header}; no subsystem registers)
goto auto_pnp_scan
:auto_pnp_endpoint
set auto-pnp-subven ${pci/${auto-pnp-addr}.0x2c.2} || goto auto_pnp_done
set auto-pnp-subdev ${pci/${auto-pnp-addr}.0x2e.2} || goto auto_pnp_done
set auto-pnp-rev ${pci/${auto-pnp-addr}.0x08.1} || goto auto_pnp_done
echo Auto PNP NIC ${auto-pnp-addr:busdevfn}: VEN_${auto-pnp-ven}&DEV_${auto-pnp-dev}&SUBSYS_${auto-pnp-subdev}${auto-pnp-subven}&REV_${auto-pnp-rev}
echo   PCI vendor=${auto-pnp-ven} device=${auto-pnp-dev} subsystem_vendor=${auto-pnp-subven} subsystem_device=${auto-pnp-subdev}
goto auto_pnp_scan
:auto_pnp_done
"##
}

