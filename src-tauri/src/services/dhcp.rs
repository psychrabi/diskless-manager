use std::net::Ipv4Addr;
use std::sync::Arc;

use crate::core::client::ClientManager;
use crate::core::config::{DhcpConfig, Settings};
use crate::services::{
    get_service_pid, is_systemd_service_running, run_sudo_command, write_with_sudo_tee,
    ServiceStatus,
};
use log::info;
use sqlx::SqlitePool;
use std::path::PathBuf;

pub struct DhcpService {
    pub(crate) settings: Arc<Settings>,
    pub(crate) db_pool: SqlitePool,
}

impl DhcpService {
    pub fn new(settings: Settings, db_pool: SqlitePool) -> Self {
        Self {
            settings: Arc::new(settings),
            db_pool,
        }
    }

    pub async fn generate_config(&self) -> anyhow::Result<()> {
        let config = &self.settings.dhcp;
        validate_dhcp_config(config)?;
        validate_server_consistency(&self.settings)?;

        let interfaces = self.settings.server.interface.join(" ");
        if interfaces.trim().is_empty() {
            anyhow::bail!("At least one DHCP interface must be configured");
        }
        for interface in &self.settings.server.interface {
            validate_interface_name(interface)?;
        }

        let dhcp_config = render_dhcp_config(config);
        let dhcp_path = PathBuf::from("/etc/dhcp/dhcpd.conf");
        if let Some(parent) = dhcp_path.parent() {
            std::fs::create_dir_all(parent)
                .map_err(|e| anyhow::anyhow!("Failed to create directory: {}", e))?;
        }

        crate::dhcp::replace_dhcp_config(&dhcp_config)
            .await
            .map_err(anyhow::Error::msg)?;

        let default_config = format!(
            "# Generated by diskless-manager\nINTERFACESv4=\"{}\"\nINTERFACESv6=\"\"\n",
            interfaces
        );
        write_with_sudo_tee("/etc/default/isc-dhcp-server", &default_config).await?;

        info!("DHCP configuration and /etc/default/isc-dhcp-server written");
        Ok(())
    }

    pub async fn start(&self) -> anyhow::Result<()> {
        run_sudo_command(["systemctl", "start", "isc-dhcp-server"]).await?;
        info!("DHCP service started");
        Ok(())
    }

    pub async fn stop(&self) -> anyhow::Result<()> {
        run_sudo_command(["systemctl", "stop", "isc-dhcp-server"]).await?;
        info!("DHCP service stopped");
        Ok(())
    }

    pub async fn reload(&self) -> anyhow::Result<()> {
        run_sudo_command(["systemctl", "restart", "isc-dhcp-server"]).await?;
        info!("DHCP service reloaded");
        Ok(())
    }

    /// Validate the complete ISC DHCP configuration, including clients.conf,
    /// before a caller reloads the service.
    pub async fn validate_config(&self) -> anyhow::Result<()> {
        validate_dhcp_config(&self.settings.dhcp)?;
        validate_server_consistency(&self.settings)?;
        for interface in &self.settings.server.interface {
            validate_interface_name(interface)?;
        }
        run_sudo_command(["dhcpd", "-t", "-cf", "/etc/dhcp/dhcpd.conf"]).await?;
        Ok(())
    }

    pub async fn get_config(&self) -> anyhow::Result<String> {
        let config_path = PathBuf::from("/etc/dhcp/dhcpd.conf");
        if config_path.exists() {
            let content = std::fs::read_to_string(&config_path)?;
            Ok(content)
        } else {
            validate_dhcp_config(&self.settings.dhcp)?;
            validate_server_consistency(&self.settings)?;
            Ok(render_dhcp_config(&self.settings.dhcp))
        }
    }

    pub async fn status(&self) -> anyhow::Result<ServiceStatus> {
        let running = is_systemd_service_running("isc-dhcp-server").await?;
        let pid = get_service_pid("isc-dhcp-server").await?;
        Ok(ServiceStatus {
            running,
            pid,
            message: if running {
                "DHCP server is running".to_string()
            } else {
                "DHCP server is not running".to_string()
            },
        })
    }

    pub async fn generate_client_configs(&self) -> anyhow::Result<()> {
        let client_manager = ClientManager::new(self.db_pool.clone());
        let clients = client_manager.list().await?;
        let server_ip = self.settings.dhcp.next_server_ip.trim();
        let server_ip = if server_ip.is_empty() {
            self.settings.server.ip_address.trim()
        } else {
            server_ip
        };
        let client_config = clients
            .into_iter()
            .filter(|client| client.enabled && !client.ip.is_empty() && client.ip != "N/A")
            .filter_map(|client| {
                client
                    .target_iqn
                    .as_deref()
                    .filter(|iqn| !iqn.trim().is_empty())
                    .map(|iqn| {
                        crate::dhcp::create_dhcp_entry_for_server(
                            &client.name,
                            &client.mac,
                            &client.ip,
                            iqn,
                            server_ip,
                        )
                    })
            })
            .collect::<Vec<_>>()
            .join("\n\n");

        crate::dhcp::replace_dhcp_clients_config(&format!("{client_config}\n"))
            .await
            .map_err(anyhow::Error::msg)?;

        info!("Static DHCP client configuration validated and written");
        Ok(())
    }
}

