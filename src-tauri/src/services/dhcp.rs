fn validate_dhcp_config(config: &DhcpConfig) -> anyhow::Result<()> {
    let subnet = parse_ipv4("subnet_ip", &config.subnet_ip)?;
    let mask = parse_ipv4("subnet_mask", &config.subnet_mask)?;
    let mask_u32 = u32::from(mask);

    if mask_u32 == 0 || (mask_u32 & (mask_u32 + 1)) != 0 {
        anyhow::bail!("subnet_mask must be a contiguous non-zero IPv4 netmask");
    }

    let network = u32::from(subnet) & mask_u32;
    if network != u32::from(subnet) {
        anyhow::bail!("subnet_ip {} is not the network address for {}", subnet, mask);
    }

    let broadcast = network | !mask_u32;
    let configured_broadcast = parse_ipv4("broadcast_ip", &config.broadcast_ip)?;
    if u32::from(configured_broadcast) != broadcast {
        anyhow::bail!(
            "broadcast_ip {} does not match subnet {}/{}",
            configured_broadcast,
            subnet,
            mask
        );
    }

    let start = parse_ipv4("start_ip", &config.start_ip)?;
    let end = parse_ipv4("end_ip", &config.end_ip)?;
    if u32::from(start) > u32::from(end) {
        anyhow::bail!("start_ip must not be greater than end_ip");
    }
    if u32::from(start) <= network || u32::from(end) >= broadcast {
        anyhow::bail!("DHCP pool must be inside the subnet and exclude network/broadcast addresses");
    }
    if !in_subnet(u32::from(start), network, mask_u32)
        || !in_subnet(u32::from(end), network, mask_u32)
    {
        anyhow::bail!("DHCP pool must be inside the configured subnet");
    }

    let gateway = parse_ipv4("gateway_ip", &config.gateway_ip)?;
    if !in_subnet(u32::from(gateway), network, mask_u32) {
        anyhow::bail!("gateway_ip {} is outside the configured subnet", gateway);
    }

    parse_ipv4("next_server_ip", &config.next_server_ip)?;
    parse_ipv4("boot_server_ip", &config.boot_server_ip)?;
    parse_ipv4("dns_server1", &config.dns_server1)?;
    parse_ipv4("dns_server2", &config.dns_server2)?;

    for value in [
        &config.boot_script,
        &config.boot_file_legacy,
        &config.boot_file_uefi32,
        &config.boot_file_uefi64,
    ] {
        validate_boot_filename(value)?;
    }

    Ok(())
}

fn validate_server_consistency(settings: &Settings) -> anyhow::Result<()> {
    let server_ip = parse_ipv4("server.ip_address", &settings.server.ip_address)?;
    let server_mask = parse_ipv4("server.netmask", &settings.server.netmask)?;
    let server_gateway = parse_ipv4("server.gateway", &settings.server.gateway)?;
    let dhcp = &settings.dhcp;

    if settings.server.interface.is_empty() {
        anyhow::bail!("server.interface must contain at least one interface");
    }

    if server_ip != parse_ipv4("dhcp.boot_server_ip", &dhcp.boot_server_ip)? {
        anyhow::bail!(
            "server.ip_address ({server_ip}) must match dhcp.boot_server_ip ({})",
            dhcp.boot_server_ip
        );
    }
    if server_ip != parse_ipv4("dhcp.next_server_ip", &dhcp.next_server_ip)? {
        anyhow::bail!(
            "server.ip_address ({server_ip}) must match dhcp.next_server_ip ({})",
            dhcp.next_server_ip
        );
    }
    if server_mask != parse_ipv4("dhcp.subnet_mask", &dhcp.subnet_mask)? {
        anyhow::bail!(
            "server.netmask ({server_mask}) must match dhcp.subnet_mask ({})",
            dhcp.subnet_mask
        );
    }
    if server_gateway != parse_ipv4("dhcp.gateway_ip", &dhcp.gateway_ip)? {
        anyhow::bail!(
            "server.gateway ({server_gateway}) must match dhcp.gateway_ip ({})",
            dhcp.gateway_ip
        );
    }

    Ok(())
}

fn parse_ipv4(field: &str, value: &str) -> anyhow::Result<Ipv4Addr> {
    value
        .trim()
        .parse::<Ipv4Addr>()
        .map_err(|error| anyhow::anyhow!("{} must be a valid IPv4 address: {}", field, error))
}

fn in_subnet(value: u32, network: u32, mask: u32) -> bool {
    value & mask == network
}

fn validate_interface_name(value: &str) -> anyhow::Result<()> {
    let value = value.trim();
    if value.is_empty()
        || value.len() > 15
        || !value
            .chars()
            .all(|character| character.is_ascii_alphanumeric() || matches!(character, '_' | '-' | '.' | ':'))
    {
        anyhow::bail!("invalid network interface name: {value:?}");
    }
    Ok(())
}

fn validate_boot_filename(value: &str) -> anyhow::Result<()> {
    let value = value.trim();
    if value.is_empty()
        || value == "."
        || value == ".."
        || value.starts_with('/')
        || value.contains("..")
        || value.contains('/')
        || value.contains('\\')
        || value.contains('"')
        || value.contains(';')
        || value.chars().any(char::is_whitespace)
    {
        anyhow::bail!("boot filename must be a safe relative filename: {value:?}");
    }
    Ok(())
}

#[expect(
    dead_code,
    reason = "Utility function kept for potential future DHCP network calculations"
)]
fn calculate_network(ip: &str, netmask: &str) -> anyhow::Result<String> {
    let ip_parts: Vec<u8> = ip
        .split('.')
        .map(|s| s.parse())
        .collect::<Result<Vec<_>, _>>()?;
    let mask_parts: Vec<u8> = netmask
        .split('.')
        .map(|s| s.parse())
        .collect::<Result<Vec<_>, _>>()?;

    let network: Vec<String> = ip_parts
        .iter()
        .zip(mask_parts.iter())
        .map(|(ip, mask)| (ip & mask).to_string())
        .collect();

    Ok(network.join("."))
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn default_dhcp_config_matches_production_network() {
        let config = DhcpConfig::default();
        assert_eq!(config.subnet_ip, "192.168.1.0");
        assert_eq!(config.subnet_mask, "255.255.255.0");
        assert_eq!(config.start_ip, "192.168.1.100");
        assert_eq!(config.end_ip, "192.168.1.200");
        assert_eq!(config.gateway_ip, "192.168.1.254");
        assert_eq!(config.dns_server1, "192.168.1.254");
        assert_eq!(config.dns_server2, "9.9.9.9");
        assert_eq!(config.next_server_ip, "192.168.1.250");
        assert_eq!(config.boot_server_ip, "192.168.1.250");
    }

    #[test]
    fn default_server_config_matches_production_network() {
        let server = crate::core::config::ServerConfig::default();
        assert_eq!(server.interface, vec!["eno2"]);
        assert_eq!(server.ip_address, "192.168.1.250");
        assert_eq!(server.netmask, "255.255.255.0");
        assert_eq!(server.gateway, "192.168.1.254");
    }

    #[test]
    fn production_dhcp_config_passes_semantic_validation() {
        validate_dhcp_config(&DhcpConfig::default()).expect("default configuration must be valid");
    }

    #[test]
    fn production_server_and_dhcp_settings_are_consistent() {
        let settings = Settings::default();
        validate_server_consistency(&settings).expect("default settings must be consistent");
    }

    #[test]
    fn invalid_broadcast_is_rejected() {
        let mut config = DhcpConfig::default();
        config.broadcast_ip = "192.168.1.254".to_string();
        assert!(validate_dhcp_config(&config).is_err());
    }

    #[test]
    fn invalid_pool_order_is_rejected() {
        let mut config = DhcpConfig::default();
        config.start_ip = "192.168.1.200".to_string();
        config.end_ip = "192.168.1.100".to_string();
        assert!(validate_dhcp_config(&config).is_err());
    }

    #[test]
    fn non_contiguous_mask_is_rejected() {
        let mut config = DhcpConfig::default();
        config.subnet_mask = "255.0.255.0".to_string();
        assert!(validate_dhcp_config(&config).is_err());
    }

    #[test]
    fn unsafe_boot_filename_is_rejected() {
        let mut config = DhcpConfig::default();
        config.boot_script = "../../autoexec.ipxe".to_string();
        assert!(validate_dhcp_config(&config).is_err());
    }

    #[test]
    fn unsafe_interface_name_is_rejected() {
        assert!(validate_interface_name("eno2; rm -rf /").is_err());
        assert!(validate_interface_name("eno2").is_ok());
    }

    #[test]
    fn canonical_renderer_contains_expected_pxe_flow() {
        let rendered = render_dhcp_config(&DhcpConfig::default());
        assert!(rendered.contains("option ipxe.san-filename code 188 = string;"));
        assert!(rendered.contains("next-server 192.168.1.250;"));
        assert!(rendered.contains("filename \"http://192.168.1.250/autoexec.ipxe\";"));
        assert!(rendered.contains("filename \"undionly.kpxe\";"));
        assert!(rendered.contains("filename \"ipxe.efi\";"));
        assert!(rendered.contains("filename \"snponly.efi\";"));
        assert_eq!(rendered.matches("option ipxe.http code 19").count(), 1);
        assert!(rendered.contains("include \"/etc/dhcp/clients.conf\";"));
    }
}
