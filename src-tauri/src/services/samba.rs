use crate::core::config::Settings;
use crate::services::{get_service_pid, is_systemd_service_running, ServiceStatus};
use std::path::PathBuf;
use tokio::process::Command;

pub struct SambaService {
    settings: Settings,
}

impl SambaService {
    pub fn new(settings: Settings) -> Self {
        Self { settings }
    }

    pub async fn start(&self) -> anyhow::Result<()> {
        // Create share directory if it doesn't exist
        std::fs::create_dir_all(&self.settings.samba.share_path)?;

        // Generate and write Samba configuration
        self.generate_config().await?;

        // Start Samba services
        Command::new("pkexec")
            .args(["systemctl", "start", "smbd"])
            .status()
            .await?;

        Command::new("pkexec")
            .args(["systemctl", "start", "nmbd"])
            .status()
            .await?;

        tracing::info!("Samba service started");
        Ok(())
    }

    pub async fn stop(&self) -> anyhow::Result<()> {
        Command::new("pkexec")
            .args(["systemctl", "start", "smbd"])
            .status()
            .await?;

        Command::new("pkexec")
            .args(["systemctl", "start", "nmbd"])
            .status()
            .await?;

        tracing::info!("Samba service stopped");
        Ok(())
    }

    pub async fn reload(&self) -> anyhow::Result<()> {
        self.generate_config().await?;

        Command::new("pkexec")
            .arg("systemctl")
            .args(["restart", "smbd"])
            .status()
            .await?;

        tracing::info!("Samba service reloaded");
        Ok(())
    }

    pub async fn status(&self) -> anyhow::Result<ServiceStatus> {
        let smbd_running = is_systemd_service_running("smbd").await?;
        let nmbd_running = is_systemd_service_running("nmbd").await?;
        let running = smbd_running && nmbd_running;

        let pid = if running {
            get_service_pid("smbd").await?
        } else {
            None
        };

        Ok(ServiceStatus {
            running,
            pid,
            message: if running {
                format!("Samba server is running (smbd + nmbd)")
            } else if smbd_running {
                "Only smbd is running".to_string()
            } else if nmbd_running {
                "Only nmbd is running".to_string()
            } else {
                "Samba server is not running".to_string()
            },
        })
    }

    pub async fn get_config(&self) -> anyhow::Result<String> {
        let config_path = PathBuf::from("/etc/samba/smb.conf");
        if config_path.exists() {
            let content = std::fs::read_to_string(&config_path)?;
            Ok(content)
        } else {
            // Return default configuration if file doesn't exist
            let config = &self.settings.samba;

            let smb_conf = format!(
                r#"# Generated by diskless-boot-server
# Do not edit manually

[global]
   workgroup = {}
   server string = Diskless Boot Server
   netbios name = {}
   security = user
   map to guest = Bad User
   dns proxy = no

   # Logging
   log file = /var/log/samba/log.%m
   max log size = 1000
   logging = file

[{}]
   path = {}
   browseable = yes
   writable = {}
   guest ok = {}
   read only = {}
   create mask = 0755
   directory mask = 0755
   force user = nobody
   force group = nogroup
"#,
                config.workgroup,
                self.settings.server.hostname,
                config.share_name,
                config.share_path.display(),
                if config.read_only { "no" } else { "yes" },
                if config.guest_ok { "yes" } else { "no" },
                if config.read_only { "yes" } else { "no" },
            );
            Ok(smb_conf)
        }
    }

    pub async fn generate_config(&self) -> anyhow::Result<()> {
        let config = &self.settings.samba;

        let smb_conf = format!(
            r#"# Generated by diskless-boot-server
# Do not edit manually

[global]
   workgroup = {}
   server string = Diskless Boot Server
   netbios name = {}
   security = user
   map to guest = Bad User
   dns proxy = no
   
   # Logging
   log file = /var/log/samba/log.%m
   max log size = 1000
   logging = file

[{}]
   path = {}
   browseable = yes
   writable = {}
   guest ok = {}
   read only = {}
   create mask = 0755
   directory mask = 0755
   force user = nobody
   force group = nogroup
"#,
            config.workgroup,
            self.settings.server.hostname,
            config.share_name,
            config.share_path.display(),
            if config.read_only { "no" } else { "yes" },
            if config.guest_ok { "yes" } else { "no" },
            if config.read_only { "yes" } else { "no" },
        );

        // Use pkexec to write to system configuration file
        use tokio::process::Command;
        let mut child = Command::new("pkexec")
            .arg("tee")
            .arg("/etc/samba/smb.conf")
            .stdin(std::process::Stdio::piped())
            .stdout(std::process::Stdio::null())
            .spawn()
            .map_err(|e| anyhow::anyhow!("Failed to spawn pkexec tee: {}", e))?;

        if let Some(ref mut stdin) = child.stdin {
            use tokio::io::AsyncWriteExt;
            stdin
                .write_all(smb_conf.as_bytes())
                .await
                .map_err(|e| anyhow::anyhow!("Failed to write config to stdin: {}", e))?;
            stdin
                .flush()
                .await
                .map_err(|e| anyhow::anyhow!("Failed to flush stdin: {}", e))?;
        }

        let status = child
            .wait()
            .await
            .map_err(|e| anyhow::anyhow!("Failed to wait for pkexec tee: {}", e))?;

        if !status.success() {
            return Err(anyhow::anyhow!(
                "Failed to write Samba config file with pkexec tee"
            ));
        }

        tracing::info!("Samba configuration written to /etc/samba/smb.conf");
        Ok(())
    }
}
